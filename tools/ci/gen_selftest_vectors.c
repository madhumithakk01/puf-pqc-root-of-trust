/*
 * Generates src/rot/rot_selftest_vectors.h: known answers for the RoT's
 * on-target self-test. Run once and commit the header; the self-test then
 * checks the board's ML-DSA-44, ML-KEM-512 and SHAKE256 against values made
 * on the host.
 *
 *   gen_selftest_vectors > src/rot/rot_selftest_vectors.h
 */

#include "rot/rot_keys.h"
#include "rot/rot_rng.h"
#include "fips202.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

int PQCLEAN_MLDSA44_CLEAN_crypto_sign_signature(uint8_t *sig, size_t *siglen, const uint8_t *m, size_t mlen, const uint8_t *sk);
int PQCLEAN_MLKEM512_CLEAN_crypto_kem_enc(uint8_t *ct, uint8_t *ss, const uint8_t *pk);

static void raw(void *c, uint8_t *b, size_t n)
{
    (void)c;
    for (size_t i = 0; i < n; i++) b[i] = (uint8_t)(i * 37 + 11);
}

static void arr(const char *name, const uint8_t *d, size_t n)
{
    printf("static const uint8_t %s[%zu] = {", name, n);
    for (size_t i = 0; i < n; i++) printf("%s0x%02x,", i % 16 ? "" : "\n    ", d[i]);
    printf("\n};\n\n");
}

int main(void)
{
    static rot_keys k;
    uint8_t uds[32], sig[ROT_DSA_SIG], ct[ROT_KEM_CT], ss[32], sh[32];
    const uint8_t msg[] = "rot-selftest-message-v1";
    size_t sl = 0;

    for (int i = 0; i < 32; i++) uds[i] = (uint8_t)(0xC0 ^ (i * 7));
    rot_rng_init(raw, NULL);
    if (rot_keys_derive(uds, &k) != 0) return 1;
    PQCLEAN_MLDSA44_CLEAN_crypto_sign_signature(sig, &sl, msg, sizeof msg - 1, k.sk_dsa);
    PQCLEAN_MLKEM512_CLEAN_crypto_kem_enc(ct, ss, k.pk_kem);
    shake256(sh, 32, (const uint8_t *)"abc", 3);

    printf("/* Generated by tools/ci/gen_selftest_vectors.c. Do not edit. */\n#ifndef ROT_SELFTEST_VECTORS_H\n#define ROT_SELFTEST_VECTORS_H\n\n#include <stdint.h>\n\n");
    arr("st_uds", uds, 32);
    arr("st_fpr_dsa", k.fpr_dsa, 32);
    arr("st_fpr_kem", k.fpr_kem, 32);
    arr("st_shake_abc", sh, 32);
    arr("st_pk_dsa", k.pk_dsa, ROT_DSA_PK);
    arr("st_sig", sig, sl);
    arr("st_sk_kem", k.sk_kem, ROT_KEM_SK);
    arr("st_ct", ct, ROT_KEM_CT);
    arr("st_ss", ss, 32);
    printf("static const uint8_t st_msg[] = \"rot-selftest-message-v1\";\n#define ST_MSG_LEN %zu\n\n#endif\n", sizeof msg - 1);
    return 0;
}
