#!/usr/bin/env python3
"""Generate the embedded golden trace as C source.

The golden trace is the input of the application's health self-test: the app
runs its DSP over it and reports the result to the RoT, which compares it
with the limits in the signed manifest. A regression in the DSP (for
example the 2:1 decimation bug) shows up as a wrong rate here without any
finger on the sensor.

This script writes a deterministic *synthetic* resting trace (72 beats per
minute, SpO2 97.5 %, 100 Hz, 10 s, inverted raw reflectance, baseline
wander and noise). `--from-csv` instead embeds a recorded trace: `red,ir` rows of
raw ADC values, exactly 1000 samples. The reference rate and SpO2 come from the
independent method in tools/sensor/label.py and are stored in the metadata.

usage: gen_golden.py [--from-csv FILE [--ref-bpm X] [--ref-spo2 Y]] [--out golden_trace.c]
                     [--meta golden.json]
"""

import argparse
import json
import math
import os
import random

RATE = 100
SECONDS = 10
BPM = 72.0
SPO2 = 97.5
DC_IR = 100000
PI = 0.015          # perfusion index of the IR channel
DC_RED = 90000


def pulse(phase):
    """One beat: systolic peak plus a smaller dicrotic wave, phase in [0, 1)."""
    return (math.exp(-(((phase - 0.20) / 0.07) ** 2))
            + 0.35 * math.exp(-(((phase - 0.52) / 0.10) ** 2)))


def synth():
    rng = random.Random(20261014)
    r = (110.0 - SPO2) / 25.0            # ratio of ratios for the target SpO2
    a_ir = DC_IR * PI
    a_red = DC_RED * PI * r
    period = RATE * 60.0 / BPM           # samples per beat
    red, ir = [], []
    for n in range(RATE * SECONDS):
        phase = (n % period) / period
        p = pulse(phase)
        wander = 300.0 * math.sin(2 * math.pi * 0.2 * n / RATE)
        # a beat is a dip in reflected light
        v_ir = DC_IR + wander - a_ir * p + rng.gauss(0, 25)
        v_red = DC_RED + 0.9 * wander - a_red * p + rng.gauss(0, 25)
        ir.append(max(0, min(0x3FFFF, int(round(v_ir)))))
        red.append(max(0, min(0x3FFFF, int(round(v_red)))))
    return red, ir


def from_csv(path):
    red, ir = [], []
    for line in open(path):
        line = line.strip()
        if not line or line[0] in "#r":
            continue
        a, b = line.split(",")[:2]
        red.append(int(a))
        ir.append(int(b))
    return red, ir


def emit(red, ir, path, synthetic):
    with open(path, "w", newline="\n") as f:
        f.write("/* Generated by gen_golden.py. Do not edit. */\n")
        f.write("/* %s */\n" % ("Synthetic trace." if synthetic else "Recorded trace."))
        f.write('#include "golden/golden_trace.h"\n\n')
        for name, data in (("golden_red", red), ("golden_ir", ir)):
            f.write("const uint32_t %s[GOLDEN_SAMPLES] = {\n" % name)
            for i in range(0, len(data), 10):
                f.write("    " + ", ".join(str(v) for v in data[i:i + 10]) + ",\n")
            f.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-csv")
    ap.add_argument("--ref-bpm", type=float)
    ap.add_argument("--ref-spo2", type=float)
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--out", default=os.path.join(here, "golden_trace.c"))
    ap.add_argument("--meta", default=os.path.join(here, "golden.json"))
    a = ap.parse_args()

    red, ir = from_csv(a.from_csv) if a.from_csv else synth()
    if len(red) != len(ir) or len(red) != RATE * SECONDS:
        raise SystemExit("trace must have %d samples" % (RATE * SECONDS))
    emit(red, ir, a.out, synthetic=not a.from_csv)
    meta = {
        "source": "recorded" if a.from_csv else "synthetic",
        "rate_hz": RATE,
        "samples": len(red),
        "reference_bpm": BPM if not a.from_csv else a.ref_bpm,
        "reference_spo2": SPO2 if not a.from_csv else a.ref_spo2,
    }
    with open(a.meta, "w", newline="\n") as f:
        json.dump(meta, f, indent=2)
        f.write("\n")
    print("wrote", a.out, "and", a.meta)


if __name__ == "__main__":
    main()
